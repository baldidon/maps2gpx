import { Injectable, HttpException, HttpStatus } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { RouteRequestDto } from './dto/route-request.dto.js';
import { buildGPX, GarminBuilder } from 'gpx-builder';
import {
  Point,
  Track,
  Segment,
  Metadata,
} from 'gpx-builder/dist/builder/BaseBuilder/models/index.js';
import { Link } from 'gpx-builder/dist/builder/BaseBuilder/models/Link.js';

const GRAPHHOPPER_BASE = 'https://graphhopper.com/api/1';

interface GraphHopperPath {
  distance: number;
  points: {
    coordinates: [number, number][];
  };
}

interface GraphHopperResponse {
  paths: GraphHopperPath[];
}

@Injectable()
export class GpxService {
  private apiKey: string;

  constructor(private configService: ConfigService) {
    this.apiKey = this.configService.get<string>('GRAPHHOPPER_API_KEY') || '';
    if (!this.apiKey) {
      console.warn(
        'GRAPHHOPPER_API_KEY not set. Set it in your environment variables.',
      );
    }
  }

  async routeToGpx(dto: RouteRequestDto) {
    if (!this.apiKey) {
      throw new HttpException(
        'GraphHopper API key not configured',
        HttpStatus.INTERNAL_SERVER_ERROR,
      );
    }

    if (!dto.waypoints || dto.waypoints.length < 2) {
      throw new HttpException(
        'At least 2 waypoints are required',
        HttpStatus.BAD_REQUEST,
      );
    }

    const profile = dto.profile || 'car';
    const graphHopperProfile = this.mapProfile(profile);

    const routeData = await this.fetchRoute(dto.waypoints, graphHopperProfile);

    const gpx = this.buildGpx(routeData, dto);

    return {
      gpx,
      fileName: this.sanitizeFileName(dto.routeName || 'route') + '.gpx',
      totalDistance: routeData.distance,
      totalPoints: routeData.points.length,
      points: routeData.points,
    };
  }

  private mapProfile(profile: string): string {
    const map: Record<string, string> = {
      car: 'car',
      bike: 'bike',
      foot: 'foot',
    };
    return map[profile] || 'car';
  }

  private async fetchRoute(
    waypoints: { lat: number; lng: number }[],
    profile: string,
  ): Promise<{ points: { lat: number; lng: number }[]; distance: number }> {
    const pointsParam = waypoints
      .map((wp) => `point=${wp.lat},${wp.lng}`)
      .join('&');

    const url = `${GRAPHHOPPER_BASE}/route?${pointsParam}&profile=${profile}&points_encoded=false&calc_points=true&key=${this.apiKey}`;

    const response = await fetch(url);

    if (!response.ok) {
      const errorText = await response.text();
      throw new HttpException(
        `GraphHopper API error: ${response.status} - ${errorText}`,
        HttpStatus.BAD_GATEWAY,
      );
    }

    const data = (await response.json()) as GraphHopperResponse;

    if (!data.paths || data.paths.length === 0) {
      throw new HttpException('No route found', HttpStatus.NOT_FOUND);
    }

    const bestPath = data.paths[0];
    const points = bestPath.points.coordinates.map(
      (coord: [number, number]) => ({
        lat: coord[1],
        lng: coord[0],
      }),
    );

    return {
      points,
      distance: bestPath.distance,
    };
  }

  private buildGpx(
    routeData: { points: { lat: number; lng: number }[]; distance: number },
    dto: RouteRequestDto,
  ): string {
    const gpx = new GarminBuilder();

    const trackPoints = routeData.points.map((p) => new Point(p.lat, p.lng));

    const segment = new Segment(trackPoints);
    const track = new Track([segment], {
      name: dto.routeName || 'Route from Google Maps',
    });

    gpx.setTracks([track]);
    gpx.setMetadata(
      new Metadata({
        time: new Date(),
        link: new Link('https://maps2gpx.app', {
          text: 'Generated by maps2gpx',
        }),
      }),
    );

    return buildGPX(gpx.toObject());
  }

  async resolveShortUrl(url: string): Promise<string> {
    const isShortUrl =
      url.includes('maps.app.goo.gl') ||
      url.includes('goo.gl/maps') ||
      url.includes('goo.gl');

    if (!isShortUrl) {
      return url;
    }

    try {
      const response = await fetch(url, {
        redirect: 'follow',
        headers: {
          'User-Agent':
            'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Version/17.0 Mobile/15E148 Safari/604.1',
        },
      });

      return response.url || url;
    } catch {
      return url;
    }
  }

  private sanitizeFileName(name: string): string {
    return name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');
  }
}
